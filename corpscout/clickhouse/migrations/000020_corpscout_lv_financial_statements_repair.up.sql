-- Repair migration: the production ledger advanced past 000016 (which failed on
-- first apply with a nullable ORDER BY and was fixed in-file afterward), so
-- `migrate up` will not re-run it and corpscout.lv_financial_statements is
-- missing on that database. This forward-only catch-up re-issues the corrected
-- DDL. It is a harmless no-op (CREATE TABLE IF NOT EXISTS) on fresh deploys
