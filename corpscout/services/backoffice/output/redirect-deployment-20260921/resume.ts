import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {launchRun,runStatus,listRuns} from '../../app/lib/dagster.server';
import {browserRequest} from '../../app/lib/browser-service.server';
import {chQuery} from '../../app/lib/clickhouse.server';
const folder='output/redirect-deployment-20260921';
if(existsSync(`${folder}/resumed-run.json`))throw new Error('Resume receipt already exists; inspect it instead of launching twice');
const [original]=JSON.parse(readFileSync(`${folder}/original-runs.json`,'utf8'));
const run=await runStatus(original.runId);
if(run.status!=='CANCELED')throw new Error(`Original run is ${run.status}`);
const active=await listRuns({job:'company_brave_search_job',limit:50,statuses:['STARTED','STARTING','QUEUED']});
if(active.some(r=>r.tags['processing/task_id']===original.tags['processing/task_id']))throw new Error('Same input is already processing');
const browser=await(await browserRequest('/v1/server')).json();
if(browser.version!=='0.7.4')throw new Error('Updated browser service is not active');
const checkpoint=await chQuery('SELECT count() AS total,countIf(status=\'success\') AS successful,countIf(status=\'error\') AS failed,uniqExact(input_id) AS distinct_inputs FROM corpscout.company_brave_search_results FINAL WHERE execution_id={id:UUID}',{id:original.runId});
const tags=Object.fromEntries(Object.entries(original.tags as Record<string,string>).filter(([k])=>!k.startsWith('dagster/')&&k!=='brave/execution'));
const request={job:'company_brave_search_job',runConfig:{ops:{se_company_brave_domains:{config:{execution_id:original.runId}}}},tags:{...tags,'corpscout/resumed_after':'browser-service-0.7.4'}};
writeFileSync(`${folder}/resume-request.json`,JSON.stringify({request,checkpoint},null,2));
const resumed=await launchRun(request);
writeFileSync(`${folder}/resumed-run.json`,JSON.stringify(resumed,null,2));
console.log(JSON.stringify({resumed,checkpoint,originalRunId:original.runId}));
